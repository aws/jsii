import * as fs from 'fs-extra';
import * as path from 'path';
import * as semver from 'semver';

import * as logging from './logging';
import { findDependencyDirectory, isBuiltinModule } from './util';
import { VERSION } from './version';

/**
 * Name of the file jsii-pacmak writes next to the `.jsii` assembly before packing the npm package.
 *
 * It records facts about the packages jsii-pacmak generated, so that jsii-pacmak runs on
 * downstream packages can take them into account.
 */
export const PACMAK_MANIFEST_FILE = '.jsii.pacmak.json';

/**
 * Contents of the `.jsii.pacmak.json` file.
 */
export interface PacmakManifest {
  /**
   * The minimum version of the jsii runtime required by the packages generated for this module,
   * including the requirements of all of its jsii dependencies.
   */
  readonly runtimeVersion: string;
}

/**
 * Determines the minimum jsii runtime version the packages generated for a module must depend on.
 *
 * jsii-pacmak makes the packages it generates depend on the jsii runtime at `>= <own version>`.
 * If a jsii dependency was generated by a newer jsii-pacmak, it requires a newer runtime than
 * that. Package managers that resolve the lowest applicable version from the nearest declaration
 * (e.g: NuGet) would then resolve a runtime that is too old for the dependency, so the generated
 * package must declare the highest runtime version required anywhere in its dependency closure.
 *
 * @param packageDir the directory of the module being packaged.
 * @param ownVersion the jsii runtime version this jsii-pacmak requires.
 *
 * @returns the minimum jsii runtime version.
 */
export async function resolveRuntimeVersion(
  packageDir: string,
  ownVersion: string = VERSION,
): Promise<string> {
  // Development builds of jsii-pacmak are used with locally built runtimes, versioned 0.0.0.
  if (ownVersion === '0.0.0') {
    return ownVersion;
  }

  let result = ownVersion;
  let requiredBy: string | undefined;

  const visited = new Set<string>();
  await visit(await fs.realpath(packageDir), true);

  if (requiredBy) {
    logging.info(
      `${packageDir}: requiring jsii runtime ${result} or later (required by ${requiredBy})`,
    );
  }
  return result;

  async function visit(dir: string, isRoot: boolean): Promise<void> {
    if (visited.has(dir)) {
      return;
    }
    visited.add(dir);

    const pkg = await fs.readJson(path.join(dir, 'package.json'));
    if (!pkg.jsii) {
      // Not a jsii package, so its dependencies are not jsii dependencies of the module.
      return;
    }

    if (!isRoot) {
      const required = await readRuntimeVersion(dir);
      if (required !== undefined && semver.gt(required, result)) {
        result = required;
        requiredBy = `${pkg.name}@${pkg.version}`;
      }
    }

    const bundled = new Set<string>([
      ...(pkg.bundleDependencies ?? []),
      ...(pkg.bundledDependencies ?? []),
    ]);
    const dependencies = new Set<string>([
      ...Object.keys(pkg.dependencies ?? {}),
      ...Object.keys(pkg.peerDependencies ?? {}),
    ]);

    await Promise.all(
      Array.from(dependencies)
        .filter((dep) => !bundled.has(dep) && !isBuiltinModule(dep))
        .map(async (dep) => {
          const depDir = await tryFindDependencyDirectory(dep, dir);
          if (depDir !== undefined) {
            await visit(await fs.realpath(depDir), false);
          }
        }),
    );
  }
}

/**
 * Writes the `.jsii.pacmak.json` file for a module.
 *
 * @param packageDir     the directory of the module being packaged.
 * @param runtimeVersion the minimum jsii runtime version, as returned by `resolveRuntimeVersion`.
 */
export async function writePacmakManifest(
  packageDir: string,
  runtimeVersion: string,
): Promise<void> {
  const manifest: PacmakManifest = { runtimeVersion };
  await fs.writeJson(path.join(packageDir, PACMAK_MANIFEST_FILE), manifest, {
    spaces: 2,
  });
}

/**
 * Reads the minimum jsii runtime version recorded for a jsii dependency.
 *
 * @returns the version, or `undefined` if the dependency was generated by a jsii-pacmak that did
 *          not record it, or recorded something this jsii-pacmak cannot interpret.
 */
async function readRuntimeVersion(
  packageDir: string,
): Promise<string | undefined> {
  const manifestFile = path.join(packageDir, PACMAK_MANIFEST_FILE);
  if (!(await fs.pathExists(manifestFile))) {
    return undefined;
  }

  let runtimeVersion: unknown;
  try {
    runtimeVersion = (await fs.readJson(manifestFile))?.runtimeVersion;
  } catch (e: any) {
    logging.warn(`Ignoring ${manifestFile}: ${e.message}`);
    return undefined;
  }

  if (typeof runtimeVersion !== 'string' || !semver.valid(runtimeVersion)) {
    logging.warn(
      `Ignoring ${manifestFile}: invalid runtimeVersion ${JSON.stringify(runtimeVersion)}`,
    );
    return undefined;
  }
  return runtimeVersion;
}

async function tryFindDependencyDirectory(
  dep: string,
  searchStart: string,
): Promise<string | undefined> {
  try {
    return await findDependencyDirectory(dep, searchStart);
  } catch (e: any) {
    // Some modules like `@types/node` cannot be require()d, and optional peer dependencies may
    // not be installed at all. Neither can contribute a jsii runtime requirement.
    if (
      ['MODULE_NOT_FOUND', 'ERR_PACKAGE_PATH_NOT_EXPORTED'].includes(e.code)
    ) {
      return undefined;
    }
    throw e;
  }
}
